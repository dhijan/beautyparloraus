// Regenerates products.sql from the two source CSVs at the repo root.
//   node src/db/build-products.js
// Asserts the catalogue and the Stripe payment links stay consistent, so a
// renamed product or a revoked link fails here instead of silently shipping a
// dead "Buy Now" button.
const assert = require("assert");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "../../..");

// minimal RFC4180-ish parser (catalogue descriptions contain quoted commas)
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];

    if (inQuotes) {
      if (c !== '"') field += c;
      else if (text[i + 1] === '"') {
        field += '"';
        i++;
      } else inQuotes = false;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") field += c;
  }

  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }

  return rows;
}

const readCsv = (name) =>
  parseCsv(fs.readFileSync(path.join(ROOT, name), "utf8"));

// Products whose category is not "skin". Everything else in the range is skincare.
const CATEGORY = {
  "Brow Gel": "brow",
  "Brow & Lash Serum": "brow",
  "Eyebrow Powder": "brow",
  "Eyebrow Brush": "brow",
  "Eyelash Growth Mascara": "lash",
  "ASAP Hand Sanitiser": "general",
};

const quote = (s) => (s === null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

function build() {
  // Stripe link name -> url. Inactive links are ignored; the CSV is newest-first
  // so the first active row for a name wins.
  const linkMap = new Map();

  for (const row of readCsv("payment_links.csv").slice(1)) {
    if (row.length < 6) continue;

    const [, , active, , url, name] = row;
    if (active !== "TRUE") continue;
    if (!linkMap.has(name.trim())) linkMap.set(name.trim(), url.trim());
  }

  const products = [];

  for (const row of readCsv("Product_Catalogue_with_Descriptions.csv")) {
    if (row.length < 4) continue;

    const [product, size, price, desc] = row.map((s) => s.trim());
    if (!product || !desc) continue;
    if (product === "Product" || product.startsWith("Note:")) continue;

    // Name matches the Stripe Payment Link name exactly, which both joins the
    // two files and disambiguates the 200 mL / 50 mL variants.
    const name = size ? `${product} - ${size}` : product;

    products.push({
      name,
      category: CATEGORY[product] || "skin",
      price: Number(price.replace("$", "")),
      desc,
      link: linkMap.get(name) || null,
    });
  }

  return { products, linkMap };
}

const { products, linkMap } = build();

const names = products.map((p) => p.name);
assert.strictEqual(new Set(names).size, names.length, "duplicate product names");
assert.ok(products.length > 40, `only parsed ${products.length} products`);
assert.ok(
  products.every((p) => p.price > 0 && Number.isFinite(p.price)),
  "product with an unparseable price"
);

const orphanLinks = [...linkMap.keys()].filter((n) => !names.includes(n));
assert.deepStrictEqual(orphanLinks, [], "payment links with no matching product");

fs.writeFileSync(
  path.join(__dirname, "products.sql"),
  `-- GENERATED by build-products.js — edit the CSVs, not this file.
-- Product names match the Stripe Payment Link names in payment_links.csv exactly.
-- Safe to re-run. On an existing database, run migrations.sql first.
DELETE FROM order_items WHERE product_id IN (SELECT id FROM products);
DELETE FROM products;
ALTER SEQUENCE products_id_seq RESTART WITH 1;

INSERT INTO products (name, category, price, description, payment_link)
VALUES
${products
  .map(
    (p) =>
      `(${quote(p.name)}, ${quote(p.category)}, ${p.price.toFixed(2)}, ${quote(
        p.desc
      )}, ${quote(p.link)})`
  )
  .join(",\n")};
`
);

const missing = products.filter((p) => !p.link);
console.log(`${products.length} products, ${products.length - missing.length} with payment links`);

if (missing.length) {
  console.warn(
    `\nWARNING — no Stripe payment link, these show "Enquire" instead of "Buy Now":\n  ` +
      missing.map((p) => p.name).join("\n  ")
  );
}
